-- Play tracking: every round, every hand, every decision — for stats and modeling.
--
--   strategies    named strategies a player is testing (rounds can be tagged with one)
--   rounds        one row per round dealt (bets, dealer cards, shoe/count context, result)
--   round_hands   one row per player hand in a round (several after splits)
--   decisions     one row per action the player took (hit/stand/double/split), with the
--                 basic-strategy recommendation for that exact spot

-- ---------------------------------------------------------------- strategies
create table public.strategies (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name        text not null check (char_length(btrim(name)) between 1 and 60),
  description text check (char_length(description) <= 500),
  created_at  timestamptz not null default now(),
  unique (user_id, name)
);

-- ---------------------------------------------------------------- rounds
create table public.rounds (
  id                  uuid primary key,                 -- generated by the client (idempotent retries)
  user_id             uuid not null default auth.uid() references auth.users (id) on delete cascade,
  strategy_id         uuid references public.strategies (id) on delete set null,
  started_at          timestamptz,
  played_at           timestamptz not null default now(), -- when the round was settled
  shoe_id             text,                              -- Deck of Cards API deck_id
  decks               smallint not null default 6,
  cards_remaining     integer,                           -- cards left in the shoe at the deal
  running_count       integer,                           -- Hi-Lo running count before the deal
  true_count          numeric(6,2),                      -- running count / decks remaining
  bankroll_before     numeric(12,2),
  bankroll_after      numeric(12,2),
  total_bet           numeric(12,2) not null check (total_bet > 0),
  total_payout        numeric(12,2) not null check (total_payout >= 0),
  net                 numeric(12,2) not null,
  result              text not null check (result in ('win', 'lose', 'push')),
  dealer_upcard       text,
  dealer_upcard_value smallint check (dealer_upcard_value between 2 and 11),
  dealer_cards        text[] not null,
  dealer_total        smallint,
  dealer_blackjack    boolean not null default false,
  dealer_bust         boolean not null default false,
  hand_count          smallint not null check (hand_count between 1 and 4)
);

create index rounds_user_played_idx on public.rounds (user_id, played_at desc);
create index rounds_strategy_idx on public.rounds (strategy_id);

-- ---------------------------------------------------------------- round_hands
create table public.round_hands (
  id               bigint generated always as identity primary key,
  round_id         uuid not null references public.rounds (id) on delete cascade,
  user_id          uuid not null default auth.uid() references auth.users (id) on delete cascade,
  hand_index       smallint not null check (hand_index between 0 and 3),
  from_split       boolean not null default false,
  doubled          boolean not null default false,
  bet              numeric(12,2) not null check (bet > 0),
  initial_cards    text[] not null,                    -- first two cards of the hand
  cards            text[] not null,                    -- all cards at the end
  situation        text,                               -- e.g. 'Hard 16', 'Soft 18', 'Pair 8s'
  initial_total    smallint,
  initial_soft     boolean,
  initial_pair     boolean,
  final_total      smallint not null,
  outcome          text not null check (outcome in ('blackjack', 'win', 'push', 'lose', 'bust')),
  payout           numeric(12,2) not null check (payout >= 0),
  net              numeric(12,2) not null,
  unique (round_id, hand_index)
);

create index round_hands_user_idx on public.round_hands (user_id);

-- ---------------------------------------------------------------- decisions
create table public.decisions (
  id                  bigint generated always as identity primary key,
  round_id            uuid not null references public.rounds (id) on delete cascade,
  user_id             uuid not null default auth.uid() references auth.users (id) on delete cascade,
  hand_index          smallint not null,
  seq                 smallint not null,                -- order of the decision within the round
  action              text not null check (action in ('hit', 'stand', 'double', 'split')),
  recommended         text check (recommended in ('hit', 'stand', 'double', 'split')),
  matched_basic       boolean generated always as (action = recommended) stored,
  situation           text,                             -- spot at decision time, e.g. 'Hard 12'
  player_cards        text[] not null,
  player_total        smallint not null,
  soft                boolean not null,
  pair                boolean not null,
  card_count          smallint not null,                -- cards in the hand when deciding
  dealer_upcard_value smallint check (dealer_upcard_value between 2 and 11),
  true_count          numeric(6,2),
  card_drawn          text,                             -- card received (hit/double)
  ms_to_decide        integer check (ms_to_decide >= 0),
  decided_at          timestamptz,
  unique (round_id, seq),
  foreign key (round_id, hand_index) references public.round_hands (round_id, hand_index) on delete cascade
);

create index decisions_user_idx on public.decisions (user_id);
create index decisions_hand_idx on public.decisions (round_id, hand_index);

-- ---------------------------------------------------------------- row level security
alter table public.strategies  enable row level security;
alter table public.rounds      enable row level security;
alter table public.round_hands enable row level security;
alter table public.decisions   enable row level security;

-- strategies: full control over your own
create policy "Own strategies: read"   on public.strategies for select to authenticated using ((select auth.uid()) = user_id);
create policy "Own strategies: create" on public.strategies for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Own strategies: edit"   on public.strategies for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Own strategies: delete" on public.strategies for delete to authenticated using ((select auth.uid()) = user_id);

-- rounds: read/insert/delete your own; history is append-only (no updates)
create policy "Own rounds: read"   on public.rounds for select to authenticated using ((select auth.uid()) = user_id);
create policy "Own rounds: create" on public.rounds for insert to authenticated with check (
  (select auth.uid()) = user_id
  and (strategy_id is null or exists (
    select 1 from public.strategies s where s.id = strategy_id and s.user_id = (select auth.uid())
  ))
);
create policy "Own rounds: delete" on public.rounds for delete to authenticated using ((select auth.uid()) = user_id);

create policy "Own hands: read"   on public.round_hands for select to authenticated using ((select auth.uid()) = user_id);
create policy "Own hands: create" on public.round_hands for insert to authenticated with check (
  (select auth.uid()) = user_id
  and exists (select 1 from public.rounds r where r.id = round_id and r.user_id = (select auth.uid()))
);

create policy "Own decisions: read"   on public.decisions for select to authenticated using ((select auth.uid()) = user_id);
create policy "Own decisions: create" on public.decisions for insert to authenticated with check (
  (select auth.uid()) = user_id
  and exists (select 1 from public.rounds r where r.id = round_id and r.user_id = (select auth.uid()))
);

revoke all on public.strategies, public.rounds, public.round_hands, public.decisions from anon;

-- ---------------------------------------------------------------- record_round
-- Saves a whole round (round + hands + decisions) in one transaction.
-- Runs with the caller's permissions, so the RLS policies above still apply.
-- Re-sending the same round id is a no-op, which makes client retries safe.
create or replace function public.record_round(payload jsonb)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  rid uuid := (payload ->> 'id')::uuid;
begin
  insert into public.rounds (
    id, strategy_id, started_at, played_at, shoe_id, decks, cards_remaining, running_count, true_count,
    bankroll_before, bankroll_after, total_bet, total_payout, net, result,
    dealer_upcard, dealer_upcard_value, dealer_cards, dealer_total, dealer_blackjack, dealer_bust, hand_count
  )
  select
    rid,
    nullif(p.strategy_id, '')::uuid,
    p.started_at,
    coalesce(p.played_at, now()),
    p.shoe_id, coalesce(p.decks, 6), p.cards_remaining, p.running_count, p.true_count,
    p.bankroll_before, p.bankroll_after, p.total_bet, p.total_payout, p.net, p.result,
    p.dealer_upcard, p.dealer_upcard_value, p.dealer_cards, p.dealer_total,
    coalesce(p.dealer_blackjack, false), coalesce(p.dealer_bust, false), p.hand_count
  from jsonb_to_record(payload) as p(
    strategy_id text, started_at timestamptz, played_at timestamptz, shoe_id text, decks smallint,
    cards_remaining integer, running_count integer, true_count numeric,
    bankroll_before numeric, bankroll_after numeric, total_bet numeric, total_payout numeric, net numeric,
    result text, dealer_upcard text, dealer_upcard_value smallint, dealer_cards text[], dealer_total smallint,
    dealer_blackjack boolean, dealer_bust boolean, hand_count smallint
  )
  on conflict (id) do nothing;

  if not found then
    return rid; -- already recorded
  end if;

  insert into public.round_hands (
    round_id, hand_index, from_split, doubled, bet, initial_cards, cards, situation,
    initial_total, initial_soft, initial_pair, final_total, outcome, payout, net
  )
  select rid, h.hand_index, coalesce(h.from_split, false), coalesce(h.doubled, false), h.bet,
         h.initial_cards, h.cards, h.situation, h.initial_total, h.initial_soft, h.initial_pair,
         h.final_total, h.outcome, h.payout, h.net
  from jsonb_to_recordset(payload -> 'hands') as h(
    hand_index smallint, from_split boolean, doubled boolean, bet numeric, initial_cards text[], cards text[],
    situation text, initial_total smallint, initial_soft boolean, initial_pair boolean,
    final_total smallint, outcome text, payout numeric, net numeric
  );

  insert into public.decisions (
    round_id, hand_index, seq, action, recommended, situation, player_cards, player_total, soft, pair,
    card_count, dealer_upcard_value, true_count, card_drawn, ms_to_decide, decided_at
  )
  select rid, d.hand_index, d.seq, d.action, d.recommended, d.situation, d.player_cards, d.player_total,
         d.soft, d.pair, d.card_count, d.dealer_upcard_value, d.true_count, d.card_drawn, d.ms_to_decide, d.decided_at
  from jsonb_to_recordset(coalesce(payload -> 'decisions', '[]'::jsonb)) as d(
    hand_index smallint, seq smallint, action text, recommended text, situation text, player_cards text[],
    player_total smallint, soft boolean, pair boolean, card_count smallint, dealer_upcard_value smallint,
    true_count numeric, card_drawn text, ms_to_decide integer, decided_at timestamptz
  );

  return rid;
end;
$$;

-- ---------------------------------------------------------------- get_play_stats
-- All KPIs for the signed-in player in one call.
-- p_strategy: 'all' (default), 'none' (untagged rounds) or a strategy id.
create or replace function public.get_play_stats(p_strategy text default 'all')
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
with
me as (select (select auth.uid()) as uid),
r as (
  select rd.* from public.rounds rd, me
  where rd.user_id = me.uid
    and (p_strategy = 'all'
         or (p_strategy = 'none' and rd.strategy_id is null)
         or rd.strategy_id::text = p_strategy)
),
h as (
  select hd.*, r.dealer_upcard_value, r.true_count as round_true_count
  from public.round_hands hd join r on r.id = hd.round_id
),
d as (
  select dc.*, h.net as hand_net, h.outcome as hand_outcome
  from public.decisions dc join h on h.round_id = dc.round_id and h.hand_index = dc.hand_index
),
first_d as (
  select distinct on (round_id, hand_index) round_id, hand_index, action
  from d order by round_id, hand_index, seq
),
ordered as (
  select id, result, net, played_at,
         row_number() over (order by played_at, id) as n,
         sum(net) over (order by played_at, id) as cum
  from r
),
runs as (
  select result, count(*) as len, max(n) as last_n
  from (
    select result, n, n - row_number() over (partition by result order by n) as grp
    from ordered where result <> 'push'
  ) x
  group by result, grp
)
select jsonb_build_object(
  'overview', (
    select jsonb_build_object(
      'rounds', count(*),
      'round_wins', count(*) filter (where result = 'win'),
      'round_losses', count(*) filter (where result = 'lose'),
      'round_pushes', count(*) filter (where result = 'push'),
      'wagered', coalesce(sum(total_bet), 0),
      'net', coalesce(sum(net), 0),
      'avg_bet', avg(total_bet),
      'best_round', max(net),
      'worst_round', min(net),
      'first_played', min(played_at),
      'last_played', max(played_at)
    ) from r
  ),
  'hands', (
    select jsonb_build_object(
      'hands', count(*),
      'wins', count(*) filter (where outcome = 'win'),
      'blackjacks', count(*) filter (where outcome = 'blackjack'),
      'pushes', count(*) filter (where outcome = 'push'),
      'losses', count(*) filter (where outcome = 'lose'),
      'busts', count(*) filter (where outcome = 'bust'),
      'doubles', count(*) filter (where doubled),
      'doubles_won', count(*) filter (where doubled and outcome in ('win', 'blackjack')),
      'split_hands', count(*) filter (where from_split)
    ) from h
  ),
  'decisions', (
    select jsonb_build_object(
      'total', count(*),
      'matched', count(*) filter (where matched_basic),
      'avg_ms', round(avg(ms_to_decide)),
      'by_type', coalesce((
        select jsonb_agg(jsonb_build_object('type', kind, 'total', total, 'matched', matched) order by kind)
        from (
          select case when pair then 'Pairs' when soft then 'Soft hands' else 'Hard hands' end as kind,
                 count(*) as total, count(*) filter (where matched_basic) as matched
          from d group by 1
        ) t
      ), '[]'::jsonb)
    ) from d
  ),
  'streaks', jsonb_build_object(
    'longest_win', (select coalesce(max(len), 0) from runs where result = 'win'),
    'longest_loss', (select coalesce(max(len), 0) from runs where result = 'lose'),
    'current', (select jsonb_build_object('result', result, 'length', len) from runs order by last_n desc limit 1)
  ),
  'timeline', coalesce((
    select jsonb_agg(jsonb_build_object('n', n, 'at', played_at, 'net', net, 'cum', cum) order by n)
    from (select * from ordered order by n desc limit 2000) t
  ), '[]'::jsonb),
  'by_upcard', coalesce((
    select jsonb_agg(jsonb_build_object(
      'upcard', up, 'hands', hands, 'wins', wins, 'losses', losses, 'pushes', pushes,
      'net', net, 'wagered', wagered) order by up)
    from (
      select dealer_upcard_value as up, count(*) as hands,
             count(*) filter (where outcome in ('win', 'blackjack')) as wins,
             count(*) filter (where outcome in ('lose', 'bust')) as losses,
             count(*) filter (where outcome = 'push') as pushes,
             sum(net) as net, sum(bet) as wagered
      from h where dealer_upcard_value is not null group by 1
    ) t
  ), '[]'::jsonb),
  'by_start', coalesce((
    select jsonb_agg(jsonb_build_object(
      'situation', situation, 'hands', hands, 'wins', wins, 'losses', losses, 'pushes', pushes,
      'net', net, 'wagered', wagered) order by hands desc, situation)
    from (
      select situation, count(*) as hands,
             count(*) filter (where outcome in ('win', 'blackjack')) as wins,
             count(*) filter (where outcome in ('lose', 'bust')) as losses,
             count(*) filter (where outcome = 'push') as pushes,
             sum(net) as net, sum(bet) as wagered
      from h where not from_split and situation is not null group by 1
    ) t
  ), '[]'::jsonb),
  'by_first_action', coalesce((
    select jsonb_agg(jsonb_build_object(
      'action', action, 'hands', hands, 'wins', wins, 'losses', losses, 'pushes', pushes, 'net', net)
      order by hands desc)
    from (
      select coalesce(f.action, 'none') as action, count(*) as hands,
             count(*) filter (where h.outcome in ('win', 'blackjack')) as wins,
             count(*) filter (where h.outcome in ('lose', 'bust')) as losses,
             count(*) filter (where h.outcome = 'push') as pushes,
             sum(h.net) as net
      from h left join first_d f on f.round_id = h.round_id and f.hand_index = h.hand_index
      group by 1
    ) t
  ), '[]'::jsonb),
  'mistakes', coalesce((
    select jsonb_agg(jsonb_build_object(
      'situation', situation, 'upcard', up, 'action', action, 'recommended', recommended,
      'times', times, 'net', net) order by times desc, net)
    from (
      select situation, dealer_upcard_value as up, action, recommended,
             count(*) as times, sum(hand_net) as net
      from d where not matched_basic
      group by 1, 2, 3, 4
      order by count(*) desc, sum(hand_net)
      limit 15
    ) t
  ), '[]'::jsonb),
  'by_true_count', coalesce((
    select jsonb_agg(jsonb_build_object(
      'bucket', bucket, 'rounds', rounds, 'net', net, 'wagered', wagered, 'avg_bet', avg_bet) order by bucket)
    from (
      select greatest(-3, least(3, round(true_count)))::int as bucket, count(*) as rounds,
             sum(net) as net, sum(total_bet) as wagered, round(avg(total_bet), 2) as avg_bet
      from r where true_count is not null group by 1
    ) t
  ), '[]'::jsonb),
  'by_strategy', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', id, 'name', name, 'rounds', rounds, 'wins', wins, 'net', net, 'wagered', wagered,
      'decisions', decisions, 'matched', matched) order by rounds desc)
    from (
      select s.id, coalesce(s.name, 'No strategy') as name, count(*) as rounds,
             count(*) filter (where ar.result = 'win') as wins,
             sum(ar.net) as net, sum(ar.total_bet) as wagered,
             coalesce(sum(dc.total), 0) as decisions, coalesce(sum(dc.matched), 0) as matched
      from public.rounds ar
      cross join me
      left join public.strategies s on s.id = ar.strategy_id
      left join lateral (
        select count(*) as total, count(*) filter (where x.matched_basic) as matched
        from public.decisions x where x.round_id = ar.id
      ) dc on true
      where ar.user_id = me.uid
      group by s.id, s.name
    ) t
  ), '[]'::jsonb)
);
$$;

revoke all on function public.record_round(jsonb) from public, anon;
revoke all on function public.get_play_stats(text) from public, anon;
grant execute on function public.record_round(jsonb) to authenticated;
grant execute on function public.get_play_stats(text) to authenticated;
